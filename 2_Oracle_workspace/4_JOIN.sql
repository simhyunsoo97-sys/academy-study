-- JOIN : 하나 이상의 테이블에서 데이터를 조회하는 작업
-- 사번, 사원 명, 부서 코드, 부서 명 조회
-- 나중에 포링키 라는걸 배우는데 포링키는 조인과 상관없음 부모가제공하는 데이너만쓸수잇는게 포링키
SELECT EMP_ID, EMP_NAME, DEPT_CODE
FROM EMPLOYEE;

SELECT DEPT_ID, DEPT_TITLE
FROM DEPARTMENT;

-- INNER JOIN(내부 조인) : 값이 일치하는 것들만 연결하여 조인
-- 오라클 전용 구문
SELECT EMP_ID, EMP_NAME, DEPT_CODE, DEPT_TITLE
FROM EMPLOYEE, DEPARTMENT
WHERE DEPT_CODE = DEPT_ID;

-- ANSI 표준 구문
SELECT EMP_ID, EMP_NAME, DEPT_CODE, DEPT_TITLE
FROM EMPLOYEE 
     JOIN DEPARTMENT ON(DEPT_CODE = DEPT_ID);
     
-- 사번, 사원 명, 직급 코드, 직급 명 조회
-- 오라클 전용 구문
SELECT EMP_ID, EMP_NAME, JOB_CODE, JOB_NAME
FROM EMPLOYEE,JOB
WHERE JOB_CODE = JOB_CODE;
-- ORA-00918: 열의 정의가 애매합니다

SELECT EMP_ID, EMP_NAME, JOB.JOB_CODE, JOB_NAME
FROM EMPLOYEE,JOB
WHERE EMPLOYEE.JOB_CODE = JOB.JOB_CODE;

SELECT EMP_ID, EMP_NAME, J.JOB_CODE, JOB_NAME
FROM EMPLOYEE E, JOB J
WHERE E.JOB_CODE = J.JOB_CODE;

-- ANSI 표준 구문
SELECT EMP_ID, EMP_NAME, JOB_CODE, JOB_NAME
FROM EMPLOYEE
     JOIN JOB ON(EMPLOYEE.JOB_CODE = JOB.JOB_CODE);
     
-- 부서 명과 해당 부서의 지역 명 조회
-- 오라클 전용 구문
SELECT DEPT_TITLE, LOCATION_ID
FROM DEPARTENT, LOCATION
WHERE LOCATION_ID = LOCAL_CODE;

-- ANSI 표준 구문
SELECT DEPT_TITLE, LOCAL_NAME
FROM DEPARTMENT
     JOIN LOCATION ON(LOCATION_ID = LOCAL_CODE);
     
-- OUTER JOIN (외부 조인) : 일치하지 않는 행도 조인에 포함
-- LEFT [OUTER] JOIN : 조인에 사용된 테이블 중 왼쪽에 기술된 테이블의 행 수를 기준으로 조인
SELECT EMP_NAME, DEPT_TITLE
FROM EMPLOYEE
     LEFT JOIN DEPARTMENT ON (DEPT_CODE = DEPT_ID);

SELECT EMP_NAME, DEPT_TITLE
FROM EMPLOYEE, DEPARTMENT
WHERE DEPT_CODE = DEPT_ID(+);
     
-- RIGTH [OUTER] JOIN : 조인에 사용된 테이블 중 오른쪽에 기술된 테이블의 행 수를 기준으로 조인
SELECT EMP_NAME, EMP_TITLE
FROM EMPLOYEE
     RIGHT OUTER JOIN DEPARTMENT ON (DEPT_CODE = DEPT_ID);
     
SELECT EMP_NAME, EMP_TITLE
FROM EMPLOYEE, DEPARTMENT
WHERE DEPT_CODE(+) = DEPT_ID;   
     

-- FULL [OUTER] JOIN : 조인에 사용된 모든 테이블의 행 수를 기준으로 조인
SELECT EMP_NAME, DEPT_TITLE
FROM EMPLOYEE
     FULL JOIN DEPARTMENT ON (DEPT_CODE = DEPT_ID);

SELECT EMP_NAME, DEPT_TITLE
FROM EMPLOYEE, DEPARTMENT
WHERE DEPT_CODE(+) = DEPT_ID(+);

-- 다중 조인
-- 사번, 사원 명, 부서 코드, 부서 명, 지역 명 조회
-- 오라클 전용 구문
SELECT EMP_ID, EMP_NAME, DEPT_ID, DEPT_TITLE, LOCAL_NAME
FROM EMPLOYEE, DEPARTMENT, LOCATION
WHERE DEPT_CODE = DEPT_ID
      AND LOCATION_ID = LOCAL_CODE;

-- ANSI 표준 구문
SELECT EMP_ID, EMP_NAME, DEPT_CODE, DEPT_TITLE, LOCAL_NAME
FROM EMPLOYEE
     JOIN DEPARTMENT ON(DEPT_CODE = DEPT_ID)
     JOIN LOCATION ON(LOCATION_ID = LOCAL_CODE);

-- ANSI 표준 구문으로 다중 조인 할 대는 순서 유의    
SELECT EMP_ID, EMP_NAME, DEPT_CODE, DEPT_TITLE, LOCAL_NAME
FROM EMPLOYEE
     JOIN LOCATION ON(LOCATION_ID = LOCAL_CODE)
     JOIN DEPARTMENT ON(DEPT_CODE = DEPT_ID);
     
-- 직급이 대리이면서 아시아 지역에 근무하는 직원의 사번, 이름, 직급 명, 근무 지역 명, 급여 조회
-- 오라클 전용 구문
SELECT EMP_ID, EMP
_NAME, JOB_NAME, DEPT_TITLE, LOCAL_NAME, SALARY
FROM EMPLOYEE, JOB, DEPARTMENT, LOCATION
WHERE EMPLOYEE.JOB_CODE = JOB.JOB_CODE
      AND DEPT_CODE = DEPT_ID
      AND LOCATION_ID = LOCAL_CODE
      AND JOB_NAME = '대리'
      AND LOCAL_NAME LIKE 'ASIA%';

-- ANSI 표준 구문
SELECT NATIONAL_CODE, EMP_ID, EMP_NAME, JOB_CODE, LOCAL_CODE, SALARY
FROM EMPLOYEE
     JOIN JOB USING(JOB_CODE)
     JOIN DEPARTMENT ON(DEPT_CODE = DEPT_ID)
     JOIN LOCATION ON(LOCAL_CODE =  LOCATION_ID)
WHERE JOB+NAME = '대리'
      AND LOCAL_NAME LIKE 'ASIA%';
    

