-- UPDATE : 테이블에 기록된 컬럼의 값을 수정하는 구문
-- 테이블 전체 행 개수에는 변화 없음
-- UPDATE 테이블명 SET 컬러명=바꿀값, 컬럼명=바꿀값,...
-- [WHEN 조건식];

-- EMPLOYEE_COPY테이블에서 DEPT_CODE가 D9인 행의 SALARY르 0으로 수정
UPDATE EMPLOYEE_COPY
SET SALARY = 0
WHERE DEPT_CODE = 'D9';

-- TCL(TRANSACTION CONTROL LANGUAGE) : 데이터의 작업을 제어하고 관리하는 명령어
-- COMMIT : 변경된 모든 작업을 데이터베이스에 영구적 반영
-- ROLLBACK : 변경된 모든 작업을 취소,  마지막 COMMIT 전까지 모두 취소
--            DDL(CREATE, ALTER, DROP)전까지 모두 취소
--                (DDL 명령어가 들어가면 자동 COMMIT)
-- SAVEPOINT : 특정 지점을 지정하여 전체가 아닌 지정 위치까지만 부분적 롤백 진행
ROLLBACK;
COMMIT;

-- UPDATE문에 서브쿼리 삽입 가능
-- 방명수 사원의 급여와 보너스를 유재식 사원과 동일하게 변경
UPDATE EMPLOYEE_COPY
