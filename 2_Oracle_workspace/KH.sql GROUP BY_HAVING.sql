FROM EMPLOYEE
GROUP BY DEPT_CODE;

-- 부서코드와 부서 별 보너스를 받는 사원 수 조회
SELECT DEPT_CODE, SUM(SALARY), AVG(SALARY), COUNT(*)
FROM EMPLOYEE
GROUP BY DEPT_CODE; 

-- 부서코드와 부서 별 보너스를 받는 사원 수 조회
SELECT DEPT_CODE, COUNT(BONUS)
FROM EMPLOYEE
