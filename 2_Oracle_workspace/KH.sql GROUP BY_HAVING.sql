-- EMPLOYEE테이블에서 성별과 성별 별 급여 평균, 급여 합계, 인원 수 조회 (인원 수로 내림차순)
SELECT DECODE(SUBSTR(EMP_NO, 8, 1), 1, '남', '여') 성별,
        AVG(SALARY), SUM(SALARY), COUNT(*)
FROM EMPLOYEE
--GROUP BY  DECODE(SUBSTR(EMP_NO, 8, 1), 1, '남', '여')
GROUP BY SUBSTR(EMP_NO, 8, 1);

-- 부서 코드와 급여 3000000 이상인 직원의 그룹별 평균 급여 조회
SELECT DEPT_CODE, AVG(SALARY)
FROM EMPLOYEE
WHERE SALARY >= 3000000
GROUP BY DEPT_CODE;

-- 부서 코드와 급여 평균이 3000000 이상인 그룹 조회
SELECT DEPT_CODE, AVG(SALARY)
FROM EMPLOYEE
GROUP BY DEPT_CODE
HAVING AVG(SALARY) >= 3000000;

-- 부서 별 급여 합계 중 9000000을 초과하는 부서코드와 급여 합계 조회
SELECT DEPT_CODE, SUM(SALARY)
FROM EMPLOYEE
GROUP BY DEPT_CODE
HAVING SUM(SALARY) > 9000000;

-- 집합 연산자
-- UNION : 합집합, OR 연산자를 한 결과
--INTERSECT : 교집합, AND 연산자를 한 결과
-- UNION ALL : 합집합 + 교집합 
-- MINUS : 차집합


SELECT EMP_ID, EMP_NAME
FROM EMPLOYEE
WHERE EMP_ID = 200
UNION
SELECT EMP_ID, EMP_NAME
FROM EMPLOYEE
WHERE EMP_ID = 201;

